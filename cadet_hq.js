/* ============================================================
   CADET-HQ.JS — Login / Profile creation + progress tracking
   ------------------------------------------------------------
   Shared module loaded on every page of the Cadet Quest Map.

   1) PROFILE GATE
      First/last name + unit email (e.g. 122sea@cadets.gc.ca).
      Shown at first visit and via "Switch Cadet". Stored in
      localStorage under 'cadetProfile'.

   2) PROGRESS TRACKING + BADGE HOOKS
      A localStorage.setItem interceptor watches writes to
      'cadetMapDemoCompleted' from EVERY module (script.js,
      all *_training.js pages) and syncs progress to the HQ
      API. New badge IDs detected => HQ Mail confirmation
      (visual HTML email) is generated by the backend.

   3) OFFLINE TOLERANCE
      Events are queued in localStorage and retried whenever
      the API is reachable. Nothing is lost if the API is down.

   4) HQ MAIL VIEWER + PROGRESS DISPLAY
      Floating dock (bottom-left) with cadet chip, progress
      ring, badge case and the HQ Mail inbox.

   Requires: i18n.js (tr) — loaded before this file.
   ============================================================ */
