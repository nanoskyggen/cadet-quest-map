  function renderMailList(overlay, force) {
    var listEl = overlay.querySelector('#hqMailList');
    if (!listEl) return;
    listEl.innerHTML = '<div class="hq-mail-empty">' + ICONS.mail + ' ' + esc(tr('Loading your confirmations\u2026')) + '</div>';
    fetchMail().then(function (list) {
      if (!list.length) {
        listEl.innerHTML = '<div class="hq-mail-empty">' + ICONS.mail + ' ' +
          esc(tr('No HQ mail yet \u2014 earn a badge to receive your first confirmation.')) + '</div>';
        return;
      }
      var read = getReadSet();
      listEl.innerHTML = list.map(function (m) {
        var isRead = !!read[m.id];
        var icon = m.kind === 'welcome' ? ICONS.star : ICONS.badge;
        var dt = new Date(m.createdAt);
        var dateStr = dt.toLocaleDateString('en-CA', { month: 'short', day: 'numeric' }) + ' ' +
          dt.toLocaleTimeString('en-CA', { hour: 'numeric', minute: '2-digit' });
        return '<div class="hq-mail-item' + (isRead ? ' read' : '') + '" data-id="' + m.id + '">' +
          '<div class="hq-mail-item-icon ' + (m.kind === 'welcome' ? 'welcome' : 'badge') + '">' + icon + '</div>' +
          '<div class="hq-mail-item-body">' +
          '<div class="hq-mail-item-subj">' + esc(m.subject) + '</div>' +
          '<div class="hq-mail-item-meta">' + esc(dateStr) + ' &middot; ' + esc(m.kind) + '</div>' +
          '</div>' +
          '<div class="hq-mail-item-arrow">' + (isRead ? '' : '<span class="hq-unread-dot"></span>') + '\u203a</div>' +
          '</div>';
      }).join('');
      listEl.querySelectorAll('.hq-mail-item').forEach(function (item) {
        item.addEventListener('click', function () {
          markRead(item.dataset.id);
          item.classList.add('read');
          openMailViewer(item.dataset.id, overlay);
        });
      });
      refreshMailCount();
    });
  }

  function openMailViewer(mailId, parentOverlay) {
    var body = document.querySelector('.hq-modal-body');
    if (!body) return;
    /* Local-first: if we already have the full html (offline mirror or cache),
       render it instantly — no round-trip needed. */
    var localHit = getLocalOutbox().filter(function (m) { return m.id === mailId; })[0];
    function renderMailHtml(html) {
      var frame = document.createElement('iframe');
      frame.className = 'hq-mail-frame';
      frame.setAttribute('title', 'mail');
      body.innerHTML = '';
      body.appendChild(frame);
      frame.srcdoc = html;
      refreshMailCount();
    }
    if (localHit && localHit.html) {
      renderMailHtml(localHit.html);
      return;
    }
    body.innerHTML = '<div class="hq-mail-empty">' + ICONS.mail + ' ' + esc(tr('Opening confirmation\u2026')) + '</div>';
    apiFetch('/api/mail/' + mailId, 'GET')
      .then(function (r) {
        var mail = r.mail;
        if (!mail) throw new Error('missing');
        renderMailHtml(mail.html);
      })
      .catch(function () {
        body.innerHTML = '<div class="hq-mail-empty">' + ICONS.warn + ' ' +
          esc(tr('HQ Mail is offline right now \u2014 progress is still saved on this device and will sync when the service is back.')) + '</div>';
      });
  }

