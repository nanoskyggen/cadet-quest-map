  function onMapWrite(rawValue) {
    var ids = [];
    try { ids = JSON.parse(rawValue || '[]'); } catch (e) { return; }
    if (!Array.isArray(ids)) return;
    if (knownSet === null) {
      /* First observation — baseline without emitting events */
      knownSet = ids.slice().sort(compareNum);
      markSeen(knownSet.slice());
      return;
    }
    var before = knownSet.slice().sort(compareNum);
    var after = ids.slice().sort(compareNum);
    if (JSON.stringify(before) === JSON.stringify(after)) return;

    var added = after.filter(function (id) { return before.indexOf(id) === -1; });
    knownSet = after;

    /* Quest-map reset detected (script.js resetProgress writes an empty list):
       clear the "seen badges" ledger so re-earning regenerates confirmations,
       wipe the local mirror + read state for a fresh run, and tell the API. */
    if (!added.length && !after.length && before.length && getProfile()) {
      try {
        localStorage.removeItem(SEEN_KEY);
        localStorage.removeItem(LOCAL_MAIL_KEY);
        localStorage.removeItem(MAIL_READ_KEY);
        mailCache = [];
      } catch (e) { /* best-effort */ }
      enqueue('/api/cadets/' + encodeURIComponent(getProfile().email) + '/reset', {}, 'reset');
    }

    if (added.length && getProfile()) {
      var seen = seenBadges();
      var fresh = added.filter(function (id) { return seen.indexOf(id) === -1; });
      if (fresh.length) {
        markSeen(after.slice());
        fresh.forEach(function (id) { reportBadge(id, after); });
        /* show HQ Mail alert */
        hqMailAlert(fresh[0], after.length);
      }
    }
    if (getProfile()) syncProgress(after);
  }

  function compareNum(a, b) { return a - b; }

  function reportBadge(badgeId, allIds) {
    var p = getProfile();
    if (!p) return;
    var total = 17;
    var earnedCount = allIds.length;
    var pct = Math.round((earnedCount / total) * 100);
    var badgeUrl = PROD_ASSET_ORIGIN + '/assets/badges/' + (BADGE_FILES[badgeId] || '');
    /* Offline mirror: always render the visual confirmation locally so the
       HQ Mail display works even if the API tunnel is unreachable. When the
       API is online the identical server copy takes precedence (dedup in
       mergeMail) — the cadet only ever sees one confirmation per badge. */
    try {
      var gen = buildClientBadgeMail(p, badgeId, allIds);
      addLocalMail({
        id: 'local-' + Date.now().toString(36) + Math.random().toString(36).slice(2, 6),
        to: p.email,
        toName: p.firstName + ' ' + p.lastName,
        kind: 'badge',
        badgeId: badgeId,
        createdAt: new Date().toISOString(),
        read: false,
        subject: gen.subject,
        html: gen.html
      });
    } catch (e) { /* local mirror is best-effort */ }
    refreshMailCount();
    enqueue('/api/cadets/' + encodeURIComponent(p.email) + '/badges', {
      badgeId: badgeId,
      badgeTitle: LESSON_TITLES[badgeId] || ('Training Badge #' + badgeId),
      badgeUrl: badgeUrl,
      xp: null,
      earnedBadges: allIds.map(function (id) {
        return { file: BADGE_FILES[id] || '', title: LESSON_TITLES[id] || '', url: PROD_ASSET_ORIGIN + '/assets/badges/' + (BADGE_FILES[id] || '') };
      }),
      earnedCount: earnedCount,
      total: total,
      pct: pct,
      origin: PROD_ASSET_ORIGIN
    }, 'badge');
  }

