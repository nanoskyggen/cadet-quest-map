  /* ---------------- mail inbox ---------------- */
  var mailCache = [];
  function mergeMail(serverMail) {
    /* Combine server inbox with the local offline mirror, newest first.
       Dedup rule: if the API is online, the server copy wins (authoritative);
       the local copy is only used when the server list is unreachable.
       Welcome mail dedups by kind; badge mail dedups by badgeId.
       Local entries are scoped to the current profile's unit email. */
    var me = getProfile();
    var local = getLocalOutbox().filter(function (m) { return me && m.to === me.email; });
    if (apiOnline === true && serverMail && serverMail.length) {
      /* Keep local copies of badges the server has NOT confirmed yet. */
      var serverBadges = {};
      var hasWelcome = false;
      serverMail.forEach(function (m) {
        if (m.kind === 'welcome') hasWelcome = true;
        if (m.kind === 'badge' && m.badgeId != null) serverBadges[String(m.badgeId)] = 1;
      });
      local = local.filter(function (m) {
        if (m.kind === 'welcome') return !hasWelcome;
        if (m.kind === 'badge' && m.badgeId != null) return !serverBadges[String(m.badgeId)];
        return true;
      });
    }
    var merged = serverMail.slice(0).concat(local);
    merged.sort(function (a, b) { return new Date(b.createdAt) - new Date(a.createdAt); });
    return merged;
  }
  function fetchMail() {
    var p = getProfile();
    if (!p) return Promise.resolve([]);
    if (apiOnline === false) return Promise.resolve(mergeMail(mailCache));
    return apiFetch('/api/cadets/' + encodeURIComponent(p.email) + '/mail', 'GET')
      .then(function (r) { mailCache = r.mail || []; return mergeMail(mailCache); })
      .catch(function () { return mergeMail(mailCache); });
  }
  function refreshMailCount() {
    fetchMail().then(function (list) {
      var read = getReadSet();
      var unread = list.filter(function (m) { return !read[m.id]; }).length;
      var dot = document.querySelector('.hq-badge-dot');
      if (dot) dot.style.display = unread ? '' : 'none';
      var count = document.querySelector('.hq-mail-count');
      if (count) count.textContent = unread ? String(unread) : '';
    });
  }
  function getReadSet() {
    try { return JSON.parse(localStorage.getItem(MAIL_READ_KEY) || '{}'); } catch (e) { return {}; }
  }
  function markRead(id) {
    var read = getReadSet(); read[id] = 1;
    localStorage.setItem(MAIL_READ_KEY, JSON.stringify(read));
  }

