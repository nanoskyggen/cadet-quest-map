  function enqueue(path, body, kind) {
    var q = getQueue();
    q.push({
      path: path, body: body, kind: kind || 'generic',
      at: Date.now(), tries: 0
    });
    saveQueue(q);
    flushQueue();
  }

  var flushing = false;
  function flushQueue() {
    if (flushing || apiOnline === false) return;
    flushing = true;
    var q = getQueue();
    if (!q.length) { flushing = false; if (apiOnline === null) pingApi(); return; }
    var item = q[0];
    apiFetch(item.path, 'POST', item.body).then(function (res) {
      q = getQueue(); q.shift(); saveQueue(q);
      if (apiOnline !== true) { apiOnline = true; updateDock(); }
      flushing = false;
      if (q.length) flushQueue(); else { refreshMailCount(); updateDock(); }
    }).catch(function () {
      if (apiOnline !== false) { apiOnline = false; updateDock(); }
      flushing = false;
    });
  }

  function apiFetch(path, method, body) {
    var url = apiBase + path;
    return fetch(url, {
      method: method,
      headers: { 'Content-Type': 'application/json' },
      body: body ? JSON.stringify(body) : undefined
    }).then(function (r) {
      if (!r.ok && r.status !== 404) throw new Error('HTTP ' + r.status);
      return r.json();
    });
  }

