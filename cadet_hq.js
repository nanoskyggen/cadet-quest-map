  function reportBarRow(label, pct) {
    var p = Math.max(0, Math.min(100, Math.round(pct)));
    var col = p >= 85 ? '#35a75a' : (p >= 60 ? '#2f6fbe' : (p >= 35 ? '#e0a53a' : '#d9564f'));
    return '<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="margin:0 0 10px;"><tr>' +
      '<td width="150" style="padding-right:10px;vertical-align:middle;"><p style="margin:0;color:#10233d;font-size:12px;font-weight:700;">' + esc(label) + '</p></td>' +
      '<td style="vertical-align:middle;"><table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="background:#e7ecf5;border-radius:99px;height:12px;"><tr>' +
      '<td width="' + p + '%" style="background:' + col + ';border-radius:99px;font-size:0;line-height:12px;">&nbsp;</td>' +
      '<td width="' + (100 - p) + '%" style="font-size:0;line-height:12px;">&nbsp;</td></tr></table></td>' +
      '<td width="46" align="right" style="vertical-align:middle;"><p style="margin:0;color:#10233d;font-size:12px;font-weight:800;">' + p + '%</p></td>' +
      '</tr></table>';
  }

